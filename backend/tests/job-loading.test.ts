import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createServer } from 'node:http';
import express from 'express';
import { createMockCore, mockJob, listen, closeServer } from './helpers/mock-core.js';
import { appReducer } from '../../frontend/src/state/app-reducer.js';
import { initialAppState } from '../../frontend/src/state/app-state.js';
import type { Job } from '../../frontend/src/types/job.js';
import { summarizeJob } from '../src/core-service/job-summaries.js';

test('summary polling preserves selected job details and detail requests skip the Core list', async t => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'job-loading-'));
  const core = await createMockCore();
  process.env.ENV_FILE = '/dev/null';
  process.env.SVG_TRANSFORM_CORE_URL = core.url;
  process.env.SVG_TO_HTML_ACCESS_STATE_PATH = path.join(dir, 'access-state.json');
  process.env.SVG_TO_HTML_SHOWCASE_JOB_IDS = 'a';
  const job = { ...mockJob('a'), logs: ['keep execution log'] };
  core.jobs.set('a', job);
  const { default: routes } = await import('../src/routes/jobs.js');
  const app = express(); app.use('/transformer/api', routes);
  const server = createServer(app);
  const origin = `http://127.0.0.1:${await listen(server)}/transformer/api`;
  t.after(async () => { await closeServer(server); await closeServer(core.server); await rm(dir, { recursive: true, force: true }); });
  const detail = await fetch(origin + '/jobs/a');
  assert.equal(detail.status, 200);
  const full = await detail.json() as Job;
  assert.equal(core.control.listRequests, 0);
  const list = await (await fetch(origin + '/jobs')).json() as Job[];
  assert.equal(list[0]?.__summary, true);
  assert.deepEqual(list[0]?.logs, []);
  const state = appReducer({ ...initialAppState, currentJob: full, currentJobId: 'a' }, { type: 'jobs/refreshed', jobs: list });
  assert.deepEqual(state.currentJob?.logs, ['keep execution log']);
  assert.equal(state.currentJob?.result, full.result);
  assert.equal(state.currentJob?.__summary, undefined);
  const summaryState = appReducer({ ...initialAppState, currentJob: summarizeJob(job) as Job, currentJobId: 'a' }, { type: 'jobs/refreshed', jobs: list });
  assert.equal(summaryState.currentJob?.__summary, true);
});
